// Background worker: context menu, keyboard shortcuts, and passing work to the offscreen player
// (a service worker can't play audio itself).
import { extractText, getSettings, getStatus, setStatus, MAX_CHARS } from "./common.js";

chrome.runtime.onInstalled.addListener(() => {
  chrome.contextMenus.removeAll(() => {
    chrome.contextMenus.create({ id: "read-selection", title: "Read “%s” with Resonant", contexts: ["selection"] });
    chrome.contextMenus.create({ id: "read-page", title: "Read this page with Resonant", contexts: ["page"] });
  });
  setStatus({ state: "idle" });
});

async function ensurePlayer() {
  const existing = await chrome.runtime.getContexts({ contextTypes: ["OFFSCREEN_DOCUMENT"] });
  if (existing.length) return;
  await chrome.offscreen.createDocument({ url: "offscreen.html", reasons: ["AUDIO_PLAYBACK"], justification: "Plays the speech generated by your Resonant server." });
}
const toPlayer = (msg) => chrome.runtime.sendMessage({ target: "offscreen", ...msg });

async function textFromTab(tabId) {
  try {
    const [r] = await chrome.scripting.executeScript({ target: { tabId }, func: extractText });
    return r?.result;
  } catch {
    // Browser pages (chrome://, the web store, PDFs) can't be read by extensions.
    return null;
  }
}

async function read({ tabId, text, title }) {
  // Show that something is happening straight away; reading the page can take a moment.
  const settings = await getSettings();
  const since = Date.now();
  await setStatus({ state: "loading", title, voice: settings.voice, since });
  const page = text ? { text, title, source: "selection" } : await textFromTab(tabId);
  if (!page) return setStatus({ state: "error", error: "This page can't be read by extensions. Select the text and use the right-click menu instead, or open a regular web page." });
  if (!page.text?.trim()) return setStatus({ state: "error", error: "There's no text on this page to read." });
  const truncated = page.text.length > MAX_CHARS;
  const body = truncated ? page.text.slice(0, page.text.lastIndexOf(" ", MAX_CHARS) || MAX_CHARS) : page.text;
  await setStatus({ state: "loading", title: page.title, source: page.source, truncated, chars: body.length, voice: settings.voice, since });
  await ensurePlayer();
  await toPlayer({ type: "play", text: body, settings, title: page.title });
}
async function stop() {
  const existing = await chrome.runtime.getContexts({ contextTypes: ["OFFSCREEN_DOCUMENT"] });
  if (existing.length) await toPlayer({ type: "stop" });
  await setStatus({ state: "idle" });
}

chrome.contextMenus.onClicked.addListener((info, tab) => {
  if (info.menuItemId === "read-selection") read({ tabId: tab?.id, text: info.selectionText, title: tab?.title });
  if (info.menuItemId === "read-page" && tab?.id) read({ tabId: tab.id });
});
chrome.commands.onCommand.addListener(async (command, tab) => {
  if (command === "stop") return stop();
  if (command === "read-page") {
    const t = tab || (await chrome.tabs.query({ active: true, currentWindow: true }))[0];
    if (t?.id) read({ tabId: t.id });
  }
});

let statusQueue = Promise.resolve();
chrome.runtime.onMessage.addListener((msg, sender, reply) => {
  if (msg?.target !== "background") return;
  // Player updates keep what the reading started with (when, which voice, truncated); a finished
  // or failed reading starts clean.
  // Updates are applied one at a time, in the order they arrive.
  if (msg.type === "status") {
    const s = msg.status;
    statusQueue = statusQueue.then(async () => setStatus(s.state === "idle" || s.state === "error" ? s : { ...(await getStatus()), ...s })).catch(() => {});
  }
  else if (msg.type === "read") read(msg);
  else if (msg.type === "stop") stop();
  else if (msg.type === "pause" || msg.type === "resume") toPlayer({ type: msg.type });
  reply?.({ ok: true });
});

// Badge on the toolbar icon while reading.
chrome.storage.session.onChanged.addListener((changes) => {
  const s = changes.status?.newValue;
  if (!s) return;
  chrome.action.setBadgeBackgroundColor({ color: s.state === "error" ? "#d93025" : "#111111" });
  chrome.action.setBadgeText({ text: s.state === "loading" ? "…" : s.state === "playing" ? "▶" : s.state === "paused" ? "II" : s.state === "error" ? "!" : "" });
});
